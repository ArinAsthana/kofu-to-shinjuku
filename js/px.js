const cache = {};
function path(rows) {
  let d = "";
  rows.forEach((r, y) => { for (let x = 0; x < r.length;) { if (r[x] !== "#") { x++; continue; } let n = 0; while (r[x + n] === "#") n++; d += `M${x} ${y}h${n}v1h-${n}z`; x += n; } });
  return d;
}
export function px(name, cls = "") {
  const rows = G[name] || G.eye, w = Math.max(...rows.map(r => r.length)), h = rows.length;
  const d = cache[name] || (cache[name] = path(rows));
  return `<svg class="px ${cls}" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" aria-hidden="true" shape-rendering="crispEdges"><path d="${d}"/></svg>`;
}
